#!/usr/bin/env python3
"""Generate BuiltinPresets.kt from libVLC's equalizer_presets.h.

Usage:
    python3 tools/gen_builtin_presets.py [path/to/equalizer_presets.h]

Without an argument the header is downloaded from the VLC GitHub mirror.
VLC writes "zero" as -1.11022e-15f; those values are emitted as 0.0.
"""
import re
import sys
import urllib.request
from pathlib import Path

URL = "https://raw.githubusercontent.com/videolan/vlc/master/modules/audio_filter/equalizer_presets.h"
OUT = Path(__file__).resolve().parent.parent / "app/src/main/java/app/vlcglobaleq/data/BuiltinPresets.kt"


def num(tok: str) -> float:
    v = float(tok.strip().rstrip("fF"))
    return 0.0 if abs(v) < 1e-6 else v


def main() -> None:
    if len(sys.argv) > 1:
        src = Path(sys.argv[1]).read_text()
    else:
        src = urllib.request.urlopen(URL).read().decode()

    labels = re.search(r"preset_list_text\[NB_PRESETS\]\s*=\s*\{(.*?)\};", src, re.S).group(1)
    labels = re.findall(r'N_\("([^"]+)"\)', labels)
    table = re.search(r"eqz_preset_10b\[NB_PRESETS\]\s*=\s*\{(.*)\};", src, re.S).group(1)
    entries = re.findall(r'\{\s*"(\w+)",\s*(\d+),\s*([-\d.e]+)f?,\s*\{([^}]*)\}', table)
    if len(entries) != len(labels):
        sys.exit(f"parse error: {len(entries)} presets vs {len(labels)} labels")

    lines = []
    for label, (key, nb, preamp, amps) in zip(labels, entries):
        vals = [num(a) for a in amps.split(",") if a.strip()]
        assert int(nb) == 10 and len(vals) == 10, key
        bands = ", ".join(repr(v) for v in vals)
        lines.append(f'        p("{key}", "{label}", {num(preamp)!r}, {bands}),')

    OUT.write_text(f"""package app.vlcglobaleq.data

// GENERATED by tools/gen_builtin_presets.py from libVLC modules/audio_filter/equalizer_presets.h.
// Do not edit by hand.

object BuiltinPresets {{
    private fun p(key: String, name: String, preamp: Double, vararg bands: Double) = Preset(
        id = "builtin:$key", name = name, preampDb = preamp, bandsDb = bands.toList(),
        bandSet = BandSet.ISO10, source = PresetSource.BUILTIN,
    )

    val all: List<Preset> = listOf(
{chr(10).join(lines)}
    )
}}
""")
    print(f"wrote {len(lines)} presets to {OUT}")


if __name__ == "__main__":
    main()
